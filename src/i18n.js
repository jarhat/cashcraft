let language = localStorage.getItem('ctf-language') === 'es' ? 'es' : 'en';
const originals = new WeakMap();
const attributes = new WeakMap();

export function translate(text) {
  if (language !== 'es') return text;
  if (spanish[text]) return spanish[text];
  const patterns = [
    [/^(\d+) token base units$/, '$1 unidades base de tokens'],
    [/^(\d+) base units$/, '$1 unidades base'],
    [/^(\d+) fungible-token (?:category|categories)$/, '$1 categorías de tokens fungibles'],
    [/^Wallet handshake complete · (.+)$/, 'Conexión de cartera completada · $1'],
    [/^Wallet disconnected · (.+)$/, 'Cartera desconectada · $1'],
    [/^Transaction ID: (.+)$/, 'ID de transacción: $1'],
    [/^(.+) \((\d+) base units\)$/, '$1 ($2 unidades base)'],
    [/^Send (\d+) token units$/, 'Enviar $1 unidades de tokens'],
    [/^Send (\d+) fungible token units$/, 'Enviar $1 unidades de tokens fungibles'],
    [/^Insufficient fungible tokens\. Available: (\d+)\.$/, 'Tokens fungibles insuficientes. Disponibles: $1.'],
    [/^Recipient must use (.+): for this network\.$/, 'El destinatario debe usar $1: para esta red.'],
  ];
  for (const [pattern, replacement] of patterns) {
    if (pattern.test(text)) return text.replace(pattern, replacement);
  }
  return text;
}

function translateNode(node) {
  if (node.nodeType === Node.TEXT_NODE) {
    if (['SCRIPT', 'STYLE', 'CODE'].includes(node.parentElement?.tagName)) return;
    const current = node.nodeValue;
    const previous = originals.get(node);
    const source = previous && current === previous.rendered ? previous.source : current;
    const rendered = source.replace(/\S[\s\S]*\S|\S/, (value) => translate(value.replace(/\s+/g, ' ')));
    originals.set(node, { source, rendered });
    if (current !== rendered) node.nodeValue = rendered;
    return;
  }
  if (node.nodeType !== Node.ELEMENT_NODE) return;
  for (const name of ['aria-label', 'placeholder', 'title']) {
    if (!node.hasAttribute(name)) continue;
    let saved = attributes.get(node);
    if (!saved) attributes.set(node, saved = {});
    if (!(name in saved)) saved[name] = node.getAttribute(name);
    node.setAttribute(name, translate(saved[name]));
  }
  node.childNodes.forEach(translateNode);
}

export function setLanguage(value) {
  language = value === 'es' ? 'es' : 'en';
  localStorage.setItem('ctf-language', language);
  document.documentElement.lang = language;
  document.querySelectorAll('[data-language-option]').forEach((button) => {
    button.setAttribute('aria-pressed', String(button.dataset.languageOption === language));
  });
  translateNode(document.body);
}

setLanguage(language);
new MutationObserver((mutations) => {
  for (const mutation of mutations) {
    if (mutation.type === 'characterData') translateNode(mutation.target);
    else mutation.addedNodes.forEach(translateNode);
  }
}).observe(document.body, { childList: true, characterData: true, subtree: true });
